export function activityPhrase(action: string): string {
  const known = PHRASES[action];
  if (known) return known;
  const [subject = '', verb = ''] = action.split('.');
  return `${verb.replace(/_/g, ' ')}: ${subject.replace(/_/g, ' ')}`.replace(/^: /, '');
}
